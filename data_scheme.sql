CREATE TYPE role AS ENUM (
  'author',
  'actor',
  'creator',
  'director',
  'artist'
);

CREATE TYPE ratingOption AS ENUM (
  'ONE',
  'TWO',
  'THREE',
  'FOUR',
  'FIVE'
);

CREATE TABLE "person" (
                          "name" varchar(255) PRIMARY KEY
);

CREATE TABLE "person_product" (
                                  "name" varchar(255),
                                  "product_number" varchar(255),
                                  "role" role NOT NULL,
                                  PRIMARY KEY ("name", "product_number")
);

CREATE TABLE "product" (
                           "product_number" varchar(255) PRIMARY KEY,
                           "title" varchar(255) NOT NULL,
                           "times_sold" integer NOT NULL,
                           "image" varchar(255)
);

CREATE TABLE "similar" (
                           "product_number_1" varchar(255),
                           "product_number_2" varchar(255),
                           PRIMARY KEY ("product_number_1", "product_number_2")
);

CREATE TABLE "book" (
                        "product_number" varchar(255) PRIMARY KEY,
                        "number_pages" integer NOT NULL,
                        "published_at" timestamp NOT NULL,
                        "isbn" varchar(255) NOT NULL
);

CREATE TABLE "book_publisher" (
                                  "product_number" varchar(255),
                                  "name" varchar(255),
                                  PRIMARY KEY ("product_number", "name")
);

CREATE TABLE "publisher" (
                             "name" varchar(255) PRIMARY KEY
);

CREATE TABLE "dvd" (
                       "product_number" varchar(255) PRIMARY KEY,
                       "format" varchar(255) NOT NULL,
                       "runtime" varchar(255) NOT NULL,
                       "region_code" varchar(255) NOT NULL
);

CREATE TABLE "cd" (
                      "product_number" varchar(255) PRIMARY KEY,
                      "published_at" varchar(255) NOT NULL
);

CREATE TABLE "cd_label" (
                            "product_number" varchar(255),
                            "name" varchar(255),
                            PRIMARY KEY ("product_number", "name")
);

CREATE TABLE "label" (
                         "name" varchar(255) PRIMARY KEY
);

CREATE TABLE "cd_title" (
                            "product_number" varchar(255),
                            "title" varchar(255),
                            PRIMARY KEY ("product_number", "title")
);

CREATE TABLE "title" (
                         "title" varchar(255) PRIMARY KEY
);

CREATE TABLE "category" (
                            "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            "name" varchar(255) NOT NULL,
                            "super_category" integer
);

CREATE TABLE "product_category" (
                                    "id" integer,
                                    "product_number" varchar(255),
                                    PRIMARY KEY ("id", "product_number")
);

CREATE TABLE "branch_office" (
                                 "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 "name" varchar(255) NOT NULL,
                                 "street" varchar(255) NOT NULL,
                                 "zip" varchar(255) NOT NULL
);

CREATE TABLE "customer" (
                            "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            "street" varchar(255) NOT NULL,
                            "zip" varchar(255) NOT NULL,
                            "username" varchar(255),
                            "bank_account_number" varchar(255) NOT NULL
);

CREATE TABLE "item_purchase" (
                                 "itemPurchaseId" integer PRIMARY KEY,
                                 "condition" varchar(255),
                                 "branch_office_id" integer,
                                 "product_number" varchar(255),
                                 "bought_at" timestamp,
                                 "count" integer NOT NULL
);

CREATE TABLE "order" (
                         "id" integer,
                         "itemPurchaseId" integer,
                         PRIMARY KEY ("itemPurchaseId", "id")
);

CREATE TABLE "rating" (
                          "id" integer,
                          "product_number" varchar(255),
                          "branch_office_id" integer,
                          "condition" varchar(255),
                          "rating" ratingOption NOT NULL,
                          "description" text,
                          "rated_at" timestamp NOT NULL,
                          PRIMARY KEY ("id", "product_number", "branch_office_id", "condition")
);

CREATE TABLE "condition" (
                             "product_number" varchar(255),
                             "branch_office_id" integer,
                             "condition" varchar(255),
                             "price" integer,
                             "count" integer NOT NULL,
                             "currency" varchar(255),
                             PRIMARY KEY ("product_number", "branch_office_id", "condition")
);

CREATE UNIQUE INDEX ON "branch_office" ("name", "street", "zip");

CREATE UNIQUE INDEX ON "item_purchase" ("condition", "branch_office_id", "product_number", "bought_at");

